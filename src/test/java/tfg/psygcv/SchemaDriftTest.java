package tfg.psygcv;

import static org.assertj.core.api.Assertions.assertThat;

import jakarta.persistence.EntityManagerFactory;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import org.hibernate.SessionFactory;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;
import org.testcontainers.mysql.MySQLContainer;
import tfg.psygcv.support.TestcontainersConfiguration;

/**
 * Compares the schema migrated by Flyway with the schema Hibernate generates from the entities.
 *
 * <p>{@code ddl-auto: validate} only checks that tables and columns exist with compatible types.
 * This test closes that gap: Hibernate exports the entity model, through the application's own
 * {@link SessionFactory} (same naming strategies and dialect), into a second database of the same
 * MySQL container, and both schemas are compared through {@code information_schema}. Because the
 * reference is generated by the Hibernate version in use, a generator change after an upgrade also
 * shows up here; it is fixed with a new migration, never by editing an applied one.
 *
 * <p>Compared, per table (excluding {@code flyway_schema_history}):
 *
 * <ul>
 *   <li>the set of tables;
 *   <li>each column's {@code COLUMN_TYPE} (length and enum values included), {@code IS_NULLABLE}
 *       and whether {@code EXTRA} contains {@code auto_increment};
 *   <li>the column set of the primary key and of each unique constraint;
 *   <li>each foreign key, as source table and column to referenced table and column.
 * </ul>
 *
 * <p>Ignored on purpose:
 *
 * <ul>
 *   <li>column order, and constraint and index names: the baseline renamed Hibernate's hashed
 *       names to {@code uk_}/{@code fk_}, and neither affects behavior;
 *   <li>non-unique indexes: MySQL creates the foreign key indexes implicitly;
 *   <li>comments, charset and collation: the charset is set when the database is created;
 *   <li>{@code COLUMN_DEFAULT} and the rest of {@code EXTRA}: a migration may need a legitimate
 *       default (for example, to add a {@code NOT NULL} column to a table with rows) that
 *       Hibernate does not generate.
 * </ul>
 *
 * <p>Uses the same context configuration as {@link PSyGCVApplicationTests} so it shares the cached
 * context and the MySQL container. The reference database is created as root, because the
 * container's application user only has privileges on its own database.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@ActiveProfiles("test")
@Import(TestcontainersConfiguration.class)
class SchemaDriftTest {

  private static final String REFERENCE_SCHEMA = "schema_drift_reference";
  private static final String FLYWAY_HISTORY_TABLE = "flyway_schema_history";
  private static final String ROOT_USER = "root";
  private static final String ROOT_PASSWORD_ENV = "MYSQL_ROOT_PASSWORD";
  private static final String AUTO_INCREMENT = "auto_increment";

  private static final String TABLES_QUERY =
      """
          SELECT TABLE_NAME FROM information_schema.TABLES
          WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE' AND TABLE_NAME <> ?
          """;
  private static final String COLUMNS_QUERY =
      """
          SELECT TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, EXTRA
          FROM information_schema.COLUMNS
          WHERE TABLE_SCHEMA = ? AND TABLE_NAME <> ?
          """;
  private static final String KEYS_QUERY =
      """
          SELECT tc.TABLE_NAME, tc.CONSTRAINT_TYPE,
                 GROUP_CONCAT(kcu.COLUMN_NAME ORDER BY kcu.COLUMN_NAME SEPARATOR ', ')
          FROM information_schema.TABLE_CONSTRAINTS tc
          JOIN information_schema.KEY_COLUMN_USAGE kcu
            ON kcu.CONSTRAINT_SCHEMA = tc.CONSTRAINT_SCHEMA
           AND kcu.TABLE_NAME = tc.TABLE_NAME
           AND kcu.CONSTRAINT_NAME = tc.CONSTRAINT_NAME
          WHERE tc.TABLE_SCHEMA = ? AND tc.TABLE_NAME <> ?
            AND tc.CONSTRAINT_TYPE IN ('PRIMARY KEY', 'UNIQUE')
          GROUP BY tc.TABLE_NAME, tc.CONSTRAINT_NAME, tc.CONSTRAINT_TYPE
          """;
  private static final String FOREIGN_KEYS_QUERY =
      """
          SELECT TABLE_NAME, COLUMN_NAME, REFERENCED_TABLE_NAME, REFERENCED_COLUMN_NAME
          FROM information_schema.KEY_COLUMN_USAGE
          WHERE TABLE_SCHEMA = ? AND TABLE_NAME <> ? AND REFERENCED_TABLE_NAME IS NOT NULL
          """;

  @Autowired
  private MySQLContainer mysqlContainer;

  @Autowired
  private EntityManagerFactory entityManagerFactory;

  @Autowired
  private JdbcTemplate jdbcTemplate;

  @BeforeEach
  void createReferenceSchema() throws SQLException {
    executeAsRoot(
        "DROP DATABASE IF EXISTS " + REFERENCE_SCHEMA,
        "CREATE DATABASE " + REFERENCE_SCHEMA,
        "GRANT ALL PRIVILEGES ON " + REFERENCE_SCHEMA + ".* TO '"
            + mysqlContainer.getUsername() + "'@'%'");
    entityManagerFactory
        .unwrap(SessionFactory.class)
        .getSchemaManager()
        .forCatalog(REFERENCE_SCHEMA)
        .exportMappedObjects(false);
  }

  @AfterEach
  void dropReferenceSchema() throws SQLException {
    executeAsRoot("DROP DATABASE IF EXISTS " + REFERENCE_SCHEMA);
  }

  @Test
  void should_matchEntityModel_when_migrationsAreApplied() {
    SchemaSnapshot expected = snapshot(REFERENCE_SCHEMA);

    assertThat(expected.tables())
        .as("tables generated by Hibernate in %s", REFERENCE_SCHEMA)
        .isNotEmpty();
    assertThat(expected.primaryKeys())
        .as("primary keys found by the query in %s: the query found no constraints",
            REFERENCE_SCHEMA)
        .isNotEmpty();
    assertThat(expected.uniqueKeys())
        .as("unique constraints found by the query in %s: the query found no constraints",
            REFERENCE_SCHEMA)
        .isNotEmpty();
    assertThat(expected.foreignKeys())
        .as("foreign keys found by the query in %s: the query found no constraints",
            REFERENCE_SCHEMA)
        .isNotEmpty();

    String migratedSchema = jdbcTemplate.queryForObject("SELECT DATABASE()", String.class);
    SchemaSnapshot migrated = snapshot(migratedSchema);
    List<String> differences = new ArrayList<>();
    compareSets("table", migrated.tables(), expected.tables(), differences);
    compareColumns(migrated.columns(), expected.columns(), differences);
    compareSets("primary key", migrated.primaryKeys(), expected.primaryKeys(), differences);
    compareSets("unique", migrated.uniqueKeys(), expected.uniqueKeys(), differences);
    compareSets("foreign key", migrated.foreignKeys(), expected.foreignKeys(), differences);

    assertThat(differences)
        .withFailMessage(
            () -> "Migrated schema differs from the entity model (" + differences.size()
                + " differences):\n  " + String.join("\n  ", differences))
        .isEmpty();
  }

  private SchemaSnapshot snapshot(String schema) {
    Set<String> tables =
        new TreeSet<>(jdbcTemplate.queryForList(
            TABLES_QUERY, String.class, schema, FLYWAY_HISTORY_TABLE));

    Map<String, ColumnDefinition> columns = new TreeMap<>();
    jdbcTemplate.query(COLUMNS_QUERY, rs -> {
      columns.put(
          rs.getString(1) + "." + rs.getString(2),
          new ColumnDefinition(
              rs.getString(3),
              rs.getString(4),
              rs.getString(5).contains(AUTO_INCREMENT) ? "YES" : "NO"));
    }, schema, FLYWAY_HISTORY_TABLE);

    Set<String> primaryKeys = new TreeSet<>();
    Set<String> uniqueKeys = new TreeSet<>();
    jdbcTemplate.query(KEYS_QUERY, rs -> {
      String key = rs.getString(1) + " (" + rs.getString(3) + ")";
      if ("PRIMARY KEY".equals(rs.getString(2))) {
        primaryKeys.add(key);
      } else {
        uniqueKeys.add(key);
      }
    }, schema, FLYWAY_HISTORY_TABLE);

    Set<String> foreignKeys =
        new TreeSet<>(jdbcTemplate.query(
            FOREIGN_KEYS_QUERY,
            (rs, rowNum) -> rs.getString(1) + "." + rs.getString(2)
                + " -> " + rs.getString(3) + "." + rs.getString(4),
            schema, FLYWAY_HISTORY_TABLE));

    return new SchemaSnapshot(tables, columns, primaryKeys, uniqueKeys, foreignKeys);
  }

  private static void compareSets(
      String kind, Set<String> migrated, Set<String> expected, List<String> differences) {
    for (String item : expected) {
      if (!migrated.contains(item)) {
        differences.add(kind + " " + item + ": missing in migrated schema");
      }
    }
    for (String item : migrated) {
      if (!expected.contains(item)) {
        differences.add(kind + " " + item + ": not generated from the entities");
      }
    }
  }

  private static void compareColumns(
      Map<String, ColumnDefinition> migrated,
      Map<String, ColumnDefinition> expected,
      List<String> differences) {
    Set<String> names = new TreeSet<>(expected.keySet());
    names.addAll(migrated.keySet());
    for (String name : names) {
      ColumnDefinition migratedColumn = migrated.get(name);
      ColumnDefinition expectedColumn = expected.get(name);
      if (migratedColumn == null) {
        differences.add(name + ": missing in migrated schema");
      } else if (expectedColumn == null) {
        differences.add(name + ": not generated from the entities");
      } else {
        compareAttribute(name, "COLUMN_TYPE",
            migratedColumn.type(), expectedColumn.type(), differences);
        compareAttribute(name, "IS_NULLABLE",
            migratedColumn.nullable(), expectedColumn.nullable(), differences);
        compareAttribute(name, "AUTO_INCREMENT",
            migratedColumn.autoIncrement(), expectedColumn.autoIncrement(), differences);
      }
    }
  }

  private static void compareAttribute(
      String column, String attribute, String migrated, String expected, List<String> differences) {
    if (!migrated.equals(expected)) {
      differences.add(
          column + ": " + attribute + " migrated=" + migrated + " expected=" + expected);
    }
  }

  private void executeAsRoot(String... statements) throws SQLException {
    String rootPassword = mysqlContainer.getEnvMap().get(ROOT_PASSWORD_ENV);
    try (Connection connection =
             DriverManager.getConnection(mysqlContainer.getJdbcUrl(), ROOT_USER, rootPassword);
         Statement statement = connection.createStatement()) {
      for (String sql : statements) {
        statement.execute(sql);
      }
    }
  }

  private record ColumnDefinition(String type, String nullable, String autoIncrement) {
  }

  private record SchemaSnapshot(
      Set<String> tables,
      Map<String, ColumnDefinition> columns,
      Set<String> primaryKeys,
      Set<String> uniqueKeys,
      Set<String> foreignKeys) {
  }
}
